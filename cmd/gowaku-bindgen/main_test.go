const sample = `<protocol name="sample">
  <interface name="wl_thing" version="3">
    <description summary="a thing"/>
    <request name="destroy" type="destructor"/>
    <request name="bind">
      <arg name="name" type="uint"/>
      <arg name="id" type="new_id"/>
    </request>
    <request name="make" since="2">
      <arg name="id" type="new_id" interface="wl_other"/>
      <arg name="label" type="string" allow-null="true"/>
      <arg name="x" type="fixed"/>
    </request>
    <event name="moved">
      <arg name="target" type="object" interface="wl_other" allow-null="true"/>
      <arg name="keys" type="array"/>
      <arg name="fd" type="fd"/>
    </event>
    <enum name="state" bitfield="true">
      <entry name="on" value="0x1"/>
      <entry name="2d" value="2"/>
    </enum>
  </interface>
  <interface name="wl_other" version="1"/>
</protocol>`

func TestSignature(t *testing.T) {
	p, err := Parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	in := &p.Interfaces[0]
	for i, want := range []string{"", "usun", "2n?sf"} {
		if got := Signature(&in.Requests[i]); got != want {
			t.Errorf("request %d: signature %q, want %q", i, got, want)
		}
	}
	if got := Signature(&in.Events[0]); got != "?oah" {
		t.Errorf("event: signature %q, want %q", got, "?oah")
	}
	if got := types(&in.Requests[1]); len(got) != 4 {
		t.Errorf("bind has %d types, want 4 (one per letter of usun)", len(got))
	}
}

func TestGenerate(t *testing.T) {
	p, err := Parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	src, err := Generate(Options{Package: "wayland", Table: "interfaces", Tags: "linux"}, []*Protocol{p}, nil)
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	for _, want := range []string{
		"// Code generated by gowaku-bindgen; DO NOT EDIT.",
		"var interfaces [2]wlInterface",
		`wlThingInterface.set("wl_thing\x00", 3, 3,`,
		`{cstr("make\x00"), cstr("2n?sf\x00"), &[]*wlInterface{wlOtherInterface, nil, nil}[0]}`,
		"func (o wlThing) destroy(c *conn) {",
		"c.marshal(proxy(o), 0, nil, 0, marshalDestroy)",
		"func (o wlThing) bind(c *conn, name uint32, iface *wlInterface, version uint32) proxy {",
		"func (o wlThing) make(c *conn, label string, x float64) wlOther {",
		"const wlThingMakeSince = 2",
		"wlThingMoved(target wlOther, keys []byte, fd int32)",
		"wlThingStateOn  = 0x1",
		"wlThingStateN2d = 2",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("output lacks %q", want)
		}
	}
	if t.Failed() {
		t.Log(s)
	}
}

// TestProtocolsParse reads the protocols that platform/wayland generates from.
func TestProtocolsParse(t *testing.T) {
	names, err := os.ReadDir("../../platform/wayland/protocol")
	if err != nil {
		t.Fatal(err)
	}
	var all []*Protocol
	for _, n := range names {
		data, err := os.ReadFile("../../platform/wayland/protocol/" + n.Name())
		if err != nil {
			t.Fatal(err)
		}
		p, err := Parse(data)
		if err != nil {
			t.Fatalf("%s: %v", n.Name(), err)
		}
		all = append(all, p)
	}
	if _, err := Generate(Options{Package: "wayland", Table: "interfaces", Tags: "linux"}, all, nil); err != nil {
		t.Fatal(err)
	}
}

func TestGenerate_Runtime(t *testing.T) {
	p, err := Parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	src, err := Generate(Options{Package: "things", Table: "interfaces", Tags: "linux", Runtime: DefaultRuntime}, []*Protocol{p}, nil)
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	for _, want := range []string{
		`import wl "github.com/bankai-tensei/gowaku/platform/wayland"`,
		"var interfaces [2]wl.Interface",
		`wlThingInterface.Set("wl_thing", 3, []wl.Message{`,
		`{Name: "make", Signature: "2n?sf", Types: []*wl.Interface{wlOtherInterface, nil, nil}},`,
		"type wlThing wl.Proxy",
		"c.Marshal(wl.Proxy(o), 0, nil, 0, wl.MarshalDestroy)",
		"func (o wlThing) bind(c *wl.Conn, name uint32, iface *wl.Interface, version uint32) wl.Proxy {",
		"c.SetInterface(1, iface)",
		"c.SetUint(2, version)",
		"c.SetNewID(3)",
		"func listenWlThing(c *wl.Conn, o wlThing, l wlThingListener) {",
		"l.wlThingMoved(wlOther(a.Object(0)), a.Array(1), a.Int(2))",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("output lacks %q", want)
		}
	}
	// Only the runtime may touch C memory.
	for _, unwanted := range []string{"unsafe", "cstr(", "c.args", `\x00`} {
		if strings.Contains(s, unwanted) {
			t.Errorf("output has %q", unwanted)
		}
	}
	if t.Failed() {
		t.Log(s)
	}
}

