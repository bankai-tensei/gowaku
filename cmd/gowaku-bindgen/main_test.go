// TestExample regenerates the example of the README and builds it for Linux
// against platform/wayland, as a program outside gowaku would.
func TestExample(t *testing.T) {
	data, err := os.ReadFile("testdata/example-shortcut-v1.xml")
	if err != nil {
		t.Fatal(err)
	}
	p, err := Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	src, err := Generate(Options{Package: "shortcut", Table: "interfaces", Tags: "linux", Runtime: DefaultRuntime}, []*Protocol{p}, nil)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile("testdata/shortcut/shortcut_linux.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(src, want) {
		t.Error("testdata/shortcut/shortcut_linux.go is stale: run go generate in testdata/shortcut")
	}
	if testing.Short() {
		t.Skip("builds with the go command")
	}
	for _, args := range [][]string{{"build", "-o", os.DevNull}, {"vet"}} {
		cmd := exec.Command("go", append(args, "./testdata/shortcut")...)
		cmd.Env = append(os.Environ(), "GOOS=linux", "GOARCH=amd64", "CGO_ENABLED=0")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Errorf("go %s: %v\n%s", args[0], err, out)
		}
	}
}
