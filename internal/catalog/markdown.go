// docURL returns the page of pkg.go.dev for a package-qualified name such as
// "control.Button".
func docURL(name string) string {
	pkg, typ := splitName(name)
	return pkgDoc + importPath(pkg) + "#" + typ
}

// importLink is the import path of pkg as a link to its documentation.
func importLink(pkg string) string {
	return "[`" + importPath(pkg) + "`](" + pkgDoc + importPath(pkg) + ")"
}

