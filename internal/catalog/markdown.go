// anchor returns the anchor GitHub gives the heading of e, which drops the
// dot of the name.
func (e *Entry) anchor() string { return strings.ToLower(strings.ReplaceAll(e.Name, ".", "")) }

func (p Package) text(lang string) string {
	if lang == "ja" {
		return p.JA
	}
	return p.EN
}

// readme is docs/catalog/README.md, which explains the catalog in both
// languages.
func readme(pages []page) string {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString("# gowaku widget catalog / ウィジェットカタログ\n\n")
	fmt.Fprintf(&b, "- [日本語](ja/README.md)\n- [English](en/README.md)\n- [Site / サイト](%s) (search, filter, light/dark)\n\n", SiteURL+"catalog/")
	pictures := 0
	for i := range pages {
		if !pages[i].NoPicture {
			pictures++
		}
	}
	fmt.Fprintf(&b, "%d entries, %d with pictures in light and dark.\n\n", len(pages), pictures)
	b.WriteString(`## 再生成 / Regenerate

` + "```" + `
go run ./internal/cmd/catalog             # draws every picture and writes the pages
go run ./internal/cmd/catalog -pictures=false  # the pages only, from the pictures here
go run ./internal/cmd/catalog -only control.Button,control.Slider  # some pictures, all pages
go test ./internal/catalog/                # are the pages and pictures up to date?
` + "```" + `

ウィジェットの説明と例は ` + "`internal/catalog`" + ` にある。1 つのウィジェットにつき、` + "`registry.go`" + ` の 1 項目と関数 1 つを用意する。関数名は ` + "`scene`" + `、先頭を大文字にしたパッケージ名、型名をつないだもの（` + "`control.Button`" + ` なら ` + "`sceneControlButton`" + `）。項目名は ` + "`control.Button`" + ` のようにパッケージ名を付けて書く。関数の本体（` + "`// catalog:begin`" + ` と ` + "`// catalog:end`" + ` があればその間）がそのまま例のコードになるため、例は必ずコンパイルされ、画像ともずれない。テストでは、` + "`widgets`" + ` 配下のパッケージの公開ウィジェットがすべて載っていること、ページが最新であること、画像が ` + "`internal/golden`" + ` と同じ許容差の範囲で最新であることを確かめる。

The descriptions and examples live in ` + "`internal/catalog`" + `: an item of ` + "`registry.go`" + ` and a function named ` + "`scene`" + `, the package with a capital and the type (` + "`sceneControlButton`" + ` for ` + "`control.Button`" + `) for each widget. Entries name their widget with the package, as in ` + "`control.Button`" + `. The body of the function, or the part between ` + "`// catalog:begin`" + ` and ` + "`// catalog:end`" + `, is the example on the page, so the examples compile and match the pictures. The tests check that every public widget of the packages under ` + "`widgets`" + ` has an entry, that the pages are up to date, and that the pictures are, within the tolerance of ` + "`internal/golden`" + `.

## 画像 / Pictures

- ` + "`gpu/soft`" + ` を使って 2 倍の密度で描画し、ページでは半分の大きさで表示する。内容の外側は余白 16 を残して切り抜き、PNG は最大の圧縮率で書き出す。
- 文字は Go フォント（BSD ライセンス、` + "`golang.org/x/image`" + ` に同梱）だけで組む。OS のフォントを使うと環境ごとに画像が変わり、CI で検証できない。和文フォントを同梱する場合、Noto Sans CJK は OFL で使えるものの 1 ウェイトで十数 MB あり、使う字だけに絞り込んでも、説明を変えるたびに作り直す必要がある。そのため画像の中の文字は英語にし、説明文は日本語と英語の両方で書く。
- Drawn at twice the density by ` + "`gpu/soft`" + ` and shown at half size, cropped to the content with a margin of 16, and compressed as far as the PNG encoder goes.
- Text is set in the Go fonts only (BSD licensed, part of ` + "`golang.org/x/image`" + `). System fonts would change the pictures from machine to machine, out of reach of CI. A bundled CJK font such as Noto Sans CJK (OFL) costs over ten megabytes a weight, and a subset would need rebuilding with every new word, so the pictures are in English and the descriptions in both languages.
`)
	return b.String()
}

// index is the contents page of a language.
func index(lang string, pages []page) string {
	w := wordsOf(lang)
	var b strings.Builder
	b.WriteString(generated)
	fmt.Fprintf(&b, "# %s\n\n", w.title)
	fmt.Fprintf(&b, "[%s](../%s/README.md) · [%s](%s)\n\n", w.otherName, w.other, w.site, siteCatalog(lang))
	fmt.Fprintf(&b, w.intro+"\n\n", len(pages))
	fmt.Fprintf(&b, "> %s\n\n%s\n\n", w.fontNote, w.helpers)
	fmt.Fprintf(&b, "| %s | %s |\n|---|---|\n", w.category, w.widgets)
	for _, c := range Categories() {
		var links []string
		for i := range pages {
			if pages[i].Category == c.Slug {
				links = append(links, fmt.Sprintf("[%s](%s.md#%s)", pages[i].Name, c.Slug, pages[i].anchor()))
			}
		}
		fmt.Fprintf(&b, "| [%s](%s.md) | %s |\n", c.name(lang), c.Slug, strings.Join(links, " · "))
	}
	fmt.Fprintf(&b, "\n## %s\n\n%s\n\n", w.packages, w.packagesIntro)
	fmt.Fprintf(&b, "| %s | %s |\n|---|---|\n", w.pkg, w.about)
	for _, pk := range Packages() {
		fmt.Fprintf(&b, "| %s | %s |\n", importLink(pk.Name), pk.text(lang))
	}
	return b.String()
}

// categoryPage is the page of one category in a language.
func categoryPage(lang string, c Category, pages []page) string {
	w := wordsOf(lang)
	var b strings.Builder
	b.WriteString(generated)
	fmt.Fprintf(&b, "# %s\n\n", c.name(lang))
	fmt.Fprintf(&b, "[%s](README.md) · [%s](../%s/%s.md) · [%s](%s%s/)\n\n", w.back, w.otherName, w.other, c.Slug, w.site, siteCatalog(lang), c.Slug)
	fmt.Fprintf(&b, "%s\n\n> %s\n\n", c.about(lang), w.helpers)
	var links []string
	for i := range pages {
		if pages[i].Category == c.Slug {
			links = append(links, fmt.Sprintf("[%s](#%s)", pages[i].Name, pages[i].anchor()))
		}
	}
	fmt.Fprintf(&b, "%s\n", strings.Join(links, " · "))
	for i := range pages {
		p := &pages[i]
		if p.Category != c.Slug {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n%s: %s\n\n", p.Name, p.text(lang), w.pkg, importLink(p.Pkg()))
		if p.NoPicture {
			fmt.Fprintf(&b, "*%s*\n\n", w.noPicture)
		} else {
			fmt.Fprintf(&b, "<picture>\n  <source media=\"(prefers-color-scheme: dark)\" srcset=\"../img/%s-dark.png\">\n"+
				"  <img src=\"../img/%s-light.png\" alt=\"%s\" width=\"%d\">\n</picture>\n\n", p.File(), p.File(), p.Name, p.Width)
		}
		fmt.Fprintf(&b, "```go\n%s\n```\n\n", p.Example)
		refs := []string{"[`" + p.Name + "`](" + docURL(p.Name) + ")"}
		for _, a := range p.Also {
			refs = append(refs, "[`"+a+"`]("+docURL(a)+")")
		}
		fmt.Fprintf(&b, "%s: %s\n", w.see, strings.Join(refs, " · "))
	}
	return b.String()
}
