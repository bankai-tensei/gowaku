package shadertool

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"strings"
	"unicode"
)

// GoFile describes the Go file of a custom shader, which embeds what
// CompileShader wrote and creates the paint.Shader.
type GoFile struct {
	// Package is the package of the file.
	Package string
	// Name is the variable of the shader, such as Ripple.
	Name string
	// Stem is the name of the source without .hlsl, such as ripple. The
	// blobs are Stem.dxbc, Stem.spv and Stem.metal, next to the Go file.
	Stem string
	// Fallback, if set, is the function in the package that paints the shader
	// on the CPU, a paint.ShaderFallback.
	Fallback string
}

// Generate returns the formatted source of f.
func (f GoFile) Generate() ([]byte, error) {
	if !token.IsIdentifier(f.Package) {
		return nil, fmt.Errorf("package %q is not a Go identifier", f.Package)
	}
	if !token.IsIdentifier(f.Name) {
		return nil, fmt.Errorf("name %q is not a Go identifier", f.Name)
	}
	if f.Fallback != "" && !token.IsIdentifier(f.Fallback) {
		return nil, fmt.Errorf("fallback %q is not a Go identifier", f.Fallback)
	}
	if f.Stem == "" || strings.ContainsAny(f.Stem, "/\\\"`") {
		return nil, fmt.Errorf("stem %q cannot name a file to embed", f.Stem)
	}
	blob := lowerFirst(f.Name)
	fallback := "nil"
	if f.Fallback != "" {
		fallback = f.Fallback
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gowaku-shader from %s.hlsl; DO NOT EDIT.\n\n", f.Stem)
	fmt.Fprintf(&b, "package %s\n\n", f.Package)
	b.WriteString("import (\n\t_ \"embed\"\n\n\t\"github.com/bankai-tensei/gowaku/paint\"\n)\n\n")
	b.WriteString("var (\n")
	fmt.Fprintf(&b, "\t//go:embed %s.dxbc\n\t%sDXBC []byte\n", f.Stem, blob)
	fmt.Fprintf(&b, "\t//go:embed %s.spv\n\t%sSPIRV []byte\n", f.Stem, blob)
	fmt.Fprintf(&b, "\t//go:embed %s.metal\n\t%sMSL []byte\n", f.Stem, blob)
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "// %s is the custom shader of %s.hlsl.\n", f.Name, f.Stem)
	fmt.Fprintf(&b, "var %s = paint.NewShader(paint.Shader{\n", f.Name)
	fmt.Fprintf(&b, "\tName: %q,\n\tDXBC: %sDXBC,\n\tSPIRV: %sSPIRV,\n\tMSL: %sMSL,\n\tFallback: %s,\n", f.Stem, blob, blob, blob, fallback)
	b.WriteString("})\n")
	return format.Source(b.Bytes())
}

// ExportedName turns the stem of a file, such as ripple or wave_mask, into an
// exported Go name: Ripple, WaveMask.
func ExportedName(stem string) (string, error) {
	var b strings.Builder
	up := true
	for _, r := range stem {
		switch {
		case r == '_' || r == '-' || r == '.' || r == ' ':
			up = true
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			if b.Len() == 0 && unicode.IsDigit(r) {
				b.WriteString("Shader")
			}
			if up {
				r = unicode.ToUpper(r)
			}
			b.WriteRune(r)
			up = false
		default:
			return "", fmt.Errorf("%q cannot become a Go name; give one with -name", stem)
		}
	}
	if b.Len() == 0 {
		return "", errors.New("empty name; give one with -name")
	}
	return b.String(), nil
}

func lowerFirst(s string) string {
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}
