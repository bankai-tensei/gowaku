// Package shadertool holds what internal/cmd/shaderc, which compiles the
// shaders of gowaku, and cmd/gowaku-shader, which compiles custom shaders,
// share: finding fxc, dxc and spirv-cross, running them, and the prelude and
// epilogue that turn the function of a custom shader into a pixel shader.
//
// The register layout of a custom shader, the same for every backend:
//
//	HLSL                         Vulkan (SPIR-V)       Metal (MSL)
//	cbuffer GowakuFrame   b0     set 0, binding 0      [[buffer(0)]]
//	Texture2D gowakuTex1  t0     set 1, binding 0      [[texture(0)]]
//	Texture2D gowakuTex0  t1     set 2, binding 0      [[texture(1)]]
//	Texture2D gowakuBackdrop t3  set 4, binding 0      [[texture(3)]]
//
// The vertex stage is the SDF vertex shader of gowaku; its output, struct
// GowakuVaryings, is the input of the pixel shader. See
// docs/ADR/0045-shaders-svg-animated-images.md.
package shadertool

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

var (
	//go:embed hlsl/prelude.hlsli
	prelude string
	//go:embed hlsl/blend.hlsli
	blend string
	//go:embed hlsl/epilogue.hlsli
	epilogue string
)

// SPIRVBindings places the registers of HLSL for Vulkan. A set is the unit that
// a Vulkan draw call rebinds, so each texture has one of its own. The shaders of
// gowaku and custom shaders use the same layout.
var SPIRVBindings = []string{
	"-fvk-bind-register", "b0", "0", "0", "0",
	"-fvk-bind-register", "s0", "0", "1", "0",
	"-fvk-bind-register", "t0", "0", "0", "1",
	"-fvk-bind-register", "t1", "0", "0", "2",
	"-fvk-bind-register", "t2", "0", "0", "3",
	"-fvk-bind-register", "t3", "0", "0", "4",
	"-fvk-bind-register", "t4", "0", "0", "5",
}

// mslBindings places the registers of a custom shader for spirv-cross, which
// with --msl-decoration-binding takes the binding as the index in Metal: buffer
// 0, and texture n for register tn. Each goes in a set of its own, so that no
// two share a binding of one set.
var mslBindings = []string{
	"-fvk-bind-register", "b0", "0", "0", "0",
	"-fvk-bind-register", "t0", "0", "0", "1",
	"-fvk-bind-register", "t1", "0", "1", "2",
	"-fvk-bind-register", "t3", "0", "3", "3",
}

// MSLResources are the indices that the Metal source of a custom shader must
// give its resources: those of the registers of HLSL.
var MSLResources = map[string]string{
	"GowakuFrame":    "buffer(0)",
	"gowakuTex1":     "texture(0)",
	"gowakuTex0":     "texture(1)",
	"gowakuBackdrop": "texture(3)",
}

// shadePattern finds the function that a custom shader must define.
var shadePattern = regexp.MustCompile(`\bfloat4\s+shade\s*\(\s*ShaderInput\s+\w+\s*\)`)

// CheckSource reports what keeps src from being a custom shader, before a
// compiler would report it in terms of the prelude.
func CheckSource(src []byte) error {
	if !shadePattern.Match(src) {
		return errors.New("no function float4 shade(ShaderInput i): a custom shader defines it, and returns a premultiplied color")
	}
	return nil
}

// Wrap returns the pixel shader that compiles src, the source of a custom
// shader read from path. #line directives make the compilers report the lines
// of src under path.
func Wrap(src []byte, path string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by gowaku-shader; DO NOT EDIT.\n")
	b.WriteString("#line 1 \"gowaku-shader prelude\"\n")
	b.WriteString(prelude)
	b.WriteString("#line 1 \"gowaku-shader blend\"\n")
	b.WriteString(blend)
	fmt.Fprintf(&b, "#line 1 %s\n", strconv.Quote(filepath.ToSlash(path)))
	b.Write(src)
	if len(src) > 0 && src[len(src)-1] != '\n' {
		b.WriteByte('\n')
	}
	b.WriteString("#line 1 \"gowaku-shader epilogue\"\n")
	b.WriteString(epilogue)
	return b.Bytes()
}

// Run runs tool with args and returns an error holding what it printed if it
// fails.
func Run(tool string, args ...string) error {
	cmd := exec.Command(tool, args...)
	var out bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &out
	if err := cmd.Run(); err != nil {
		text := strings.TrimSpace(out.String())
		if text == "" {
			return fmt.Errorf("%s: %w", filepath.Base(tool), err)
		}
		return fmt.Errorf("%s: %w\n%s", filepath.Base(tool), err, text)
	}
	return nil
}

// DXBCArgs returns the arguments of fxc that compile src, a shader of kind vs
// or ps, to out. includes are more directories to look for #include in.
func DXBCArgs(src, out, kind string, includes ...string) []string {
	args := []string{"/nologo", "/T", kind + "_5_0", "/E", "main", "/O3"}
	for _, dir := range includes {
		args = append(args, "/I", dir)
	}
	return append(args, "/Fo", out, src)
}

// SPIRVArgs returns the arguments of dxc that compile src to out with the given
// bindings. It flips y in vertex shaders, because the clip space of Vulkan points
// down; the sources stay those of Direct3D (ADR 0012).
func SPIRVArgs(src, out, kind string, bindings []string, includes ...string) []string {
	args := []string{"-spirv", "-fspv-target-env=vulkan1.0", "-T", kind + "_6_0", "-E", "main", "-O3", "-Fo", out}
	args = append(args, bindings...)
	for _, dir := range includes {
		args = append(args, "-I", dir)
	}
	if kind == "vs" {
		args = append(args, "-fvk-invert-y")
	}
	return append(args, src)
}

// FindFXC looks on PATH and then in the newest installed Windows SDK.
func FindFXC() (string, error) {
	if path, err := exec.LookPath("fxc"); err == nil {
		return path, nil
	}
	found, err := filepath.Glob(`C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\fxc.exe`)
	if err != nil {
		return "", err
	}
	if len(found) == 0 {
		return "", errors.New("fxc not found: install the Windows SDK or add fxc to PATH")
	}
	slices.Sort(found)
	return found[len(found)-1], nil
}

// FindDXC looks on PATH and then in the Vulkan SDK. Its dxc is the build that can
// write SPIR-V.
func FindDXC() (string, error) {
	return findVulkanTool("dxc")
}

// FindSPIRVCross looks on PATH and then in the Vulkan SDK.
func FindSPIRVCross() (string, error) {
	return findVulkanTool("spirv-cross")
}

// findVulkanTool looks for name on PATH, in the Bin of $VULKAN_SDK and in the
// newest SDK under C:\VulkanSDK.
func findVulkanTool(name string) (string, error) {
	if path, err := exec.LookPath(name); err == nil {
		return path, nil
	}
	var dirs []string
	if sdk := os.Getenv("VULKAN_SDK"); sdk != "" {
		dirs = append(dirs, filepath.Join(sdk, "Bin"), filepath.Join(sdk, "bin"))
	}
	if found, err := filepath.Glob(`C:\VulkanSDK\*\Bin`); err == nil {
		slices.Sort(found)
		slices.Reverse(found)
		dirs = append(dirs, found...)
	}
	for _, dir := range dirs {
		for _, file := range []string{name + ".exe", name} {
			path := filepath.Join(dir, file)
			if info, err := os.Stat(path); err == nil && !info.IsDir() {
				return path, nil
			}
		}
	}
	return "", fmt.Errorf("%s not found: install the Vulkan SDK or add %s to PATH", name, name)
}

// Compiled is what CompileShader writes.
type Compiled struct {
	DXBC, SPIRV, MSL string
}

// CompileOptions configures CompileShader.
type CompileOptions struct {
	// FXC, DXC and SPIRVCross are the tools.
	FXC, DXC, SPIRVCross string
	// Stem is the path of the output without its extension: Stem.dxbc,
	// Stem.spv and Stem.metal.
	Stem string
	// Keep, if set, also writes the wrapped source to Stem.wrapped.hlsl.
	Keep bool
}

// CompileShader compiles the custom shader at path for every backend. Errors
// in the source name path and its lines.
func CompileShader(path string, opts CompileOptions) (Compiled, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return Compiled{}, err
	}
	if err := CheckSource(src); err != nil {
		return Compiled{}, fmt.Errorf("%s: %w", path, err)
	}
	tmp, err := os.MkdirTemp("", "gowaku-shader")
	if err != nil {
		return Compiled{}, err
	}
	defer os.RemoveAll(tmp) //nolint:errcheck // a leftover temporary directory does no harm
	wrapped := filepath.Join(tmp, "wrapped.hlsl")
	full := Wrap(src, path)
	if err := os.WriteFile(wrapped, full, 0o644); err != nil {
		return Compiled{}, err
	}
	if opts.Keep {
		if err := os.WriteFile(opts.Stem+".wrapped.hlsl", full, 0o644); err != nil {
			return Compiled{}, err
		}
	}
	dir := filepath.Dir(path)
	out := Compiled{DXBC: opts.Stem + ".dxbc", SPIRV: opts.Stem + ".spv", MSL: opts.Stem + ".metal"}
	if err := Run(opts.FXC, DXBCArgs(wrapped, out.DXBC, "ps", dir)...); err != nil {
		return Compiled{}, tidy(err, wrapped)
	}
	if err := Run(opts.DXC, SPIRVArgs(wrapped, out.SPIRV, "ps", SPIRVBindings, dir)...); err != nil {
		return Compiled{}, tidy(err, wrapped)
	}
	forMSL := filepath.Join(tmp, "msl.spv")
	if err := Run(opts.DXC, SPIRVArgs(wrapped, forMSL, "ps", mslBindings, dir)...); err != nil {
		return Compiled{}, tidy(err, wrapped)
	}
	if err := Run(opts.SPIRVCross, "--msl", "--msl-version", "20100", "--msl-decoration-binding", "--output", out.MSL, forMSL); err != nil {
		return Compiled{}, err
	}
	metal, err := os.ReadFile(out.MSL)
	if err != nil {
		return Compiled{}, err
	}
	if err := CheckMSL(metal); err != nil {
		return Compiled{}, fmt.Errorf("%s: %w", out.MSL, err)
	}
	// SPIRV-Cross ends the lines as the OS does. The Metal source is text
	// that is checked in and compared, so it gets the same bytes on every OS.
	if lf := bytes.ReplaceAll(metal, []byte("\r\n"), []byte("\n")); len(lf) != len(metal) {
		if err := os.WriteFile(out.MSL, lf, 0o644); err != nil {
			return Compiled{}, err
		}
	}
	return out, nil
}

// tidy replaces the path of the wrapped source in the messages of err, which
// only lines without a #line of their own carry.
func tidy(err error, wrapped string) error {
	msg := err.Error()
	for _, p := range []string{wrapped, filepath.ToSlash(wrapped)} {
		msg = strings.ReplaceAll(msg, p, "gowaku-shader")
	}
	return errors.New(msg)
}

// mslResource finds the resources of a Metal source and their indices.
var mslResource = regexp.MustCompile(`(\w+)\s*\[\[((?:buffer|texture|sampler)\(\d+\))\]\]`)

// CheckMSL reports a resource of the Metal source of a custom shader whose
// index is not the one of MSLResources. A resource that the shader does not
// use is left out by spirv-cross, and that is fine.
func CheckMSL(metal []byte) error {
	for _, m := range mslResource.FindAllSubmatch(metal, -1) {
		name, index := string(m[1]), string(m[2])
		want, ok := MSLResources[name]
		if !ok {
			return fmt.Errorf("unexpected resource %s [[%s]]", name, index)
		}
		if want != index {
			return fmt.Errorf("resource %s has [[%s]], want [[%s]]", name, index, want)
		}
	}
	return nil
}
