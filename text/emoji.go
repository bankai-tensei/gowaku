func hasEmojiPresentation(r rune) bool {
	if r < emojiPresentation[0][0] {
		return false
	}
	lo, hi := 0, len(emojiPresentation)
	for lo < hi {
		m := (lo + hi) / 2
		switch rg := emojiPresentation[m]; {
		case r < rg[0]:
			hi = m
		case r > rg[1]:
			lo = m + 1
		default:
			return true
		}
	}
	return false
}

// isEmojiCluster reports whether a grapheme cluster shows as emoji: its first
// character does by default and VS15 does not ask for text, or VS16 asks for
// emoji. Keycaps (1️⃣) carry VS16.
func isEmojiCluster(runes []rune) bool {
	if len(runes) == 0 {
		return false
	}
	for _, r := range runes[1:] {
		switch r {
		case variationEmoji:
			return true
		case variationText:
			return false
		}
	}
	return hasEmojiPresentation(runes[0])
}
